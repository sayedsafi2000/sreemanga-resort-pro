export type TranslationKey = keyof typeof translations;
export type TranslationCategory = keyof typeof translations.nav;

export function getTranslation(
  category: TranslationKey,
  key: string,
  lang: 'en' | 'bn'
): string {
  const cat = translations[category as TranslationKey];
  if (!cat) return key;
  
  const item = cat as Record<string, { en: string; bn: string }>;
  const trans = item[key as keyof typeof item];
  
  if (!trans) return key;
  return trans[lang] || trans.en || key;
}